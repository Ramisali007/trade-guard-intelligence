/**
 * What kind of authority stands behind a rule. The kinds are kept apart on purpose: a messaging format, a
 * documentary standard, a regulator's direction and a legal prohibition do not carry the same weight, and a gap
 * against one of them is not a breach of another. A missing document is a gap to resolve, never a finding that
 * something is prohibited.
 */
export type RuleBasis = 'REGULATORY_DIRECTION' | 'DOCUMENTARY_STANDARD' | 'MESSAGING_STANDARD' | 'REFERENCE_DATA_CHECK' | 'SANCTIONS_PROGRAMME' | 'BANK_POLICY';

